-- ============================================================
-- NICE Store - categorias gerenciadas pelo admin (rode UMA vez no SQL Editor)
-- Seguro para rodar de novo. Requer as migrações anteriores.
--
-- categories: lista de categorias da loja (leitura pública, só admin cria).
-- delete_category(): exclui uma categoria e move os produtos dela para
-- "Sem categoria" na mesma operação. "Sem categoria" não pode ser excluída.
-- ============================================================

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(trim(name)) > 0),
  position bigint generated by default as identity,
  created_at timestamptz not null default now()
);

alter table public.categories enable row level security;

drop policy if exists "categories: leitura publica" on public.categories;
create policy "categories: leitura publica" on public.categories
  for select to anon, authenticated using (true);

drop policy if exists "categories: admin insere" on public.categories;
create policy "categories: admin insere" on public.categories
  for insert to authenticated with check (public.is_admin());

-- Exclusão só pela função abaixo (ela também move os produtos).

-- Categorias iniciais, na ordem da loja.
insert into public.categories (name) values ('Camisetas') on conflict (name) do nothing;
insert into public.categories (name) values ('Moletons') on conflict (name) do nothing;
insert into public.categories (name) values ('Calças') on conflict (name) do nothing;
insert into public.categories (name) values ('Acessórios') on conflict (name) do nothing;
insert into public.categories (name) values ('Sem categoria') on conflict (name) do nothing;

-- Categorias que já estão em produtos e ainda não estão na lista.
insert into public.categories (name)
select distinct category from public.products where trim(category) <> ''
on conflict (name) do nothing;

create or replace function public.delete_category(target text)
returns integer
language plpgsql security definer set search_path = public as $$
declare
  movidos integer;
begin
  if not public.is_admin() then
    raise exception 'not admin' using errcode = '42501';
  end if;
  if target = 'Sem categoria' then
    raise exception 'protected category';
  end if;
  update public.products set category = 'Sem categoria', updated_at = now() where category = target;
  get diagnostics movidos = row_count;
  delete from public.categories where name = target;
  return movidos;
end;
$$;
revoke all on function public.delete_category(text) from public, anon;
grant execute on function public.delete_category(text) to authenticated;
